import { afterEach, expect, it } from "vitest";
import { Pool } from "pg";
import { randomUUID } from "node:crypto";
import { chmod, mkdtemp, readFile, readdir, writeFile, rm, stat } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
const run=promisify(execFile);
const cleanup:Array<()=>Promise<unknown>>=[];
afterEach(async()=>{for(const work of cleanup.reverse())await work();cleanup.length=0;});
it("backs up a consistent database, restores to an empty database and refuses corruption or overwrites",async()=>{
 if(!process.env.TEST_DATABASE_URL)throw new Error("TEST_DATABASE_URL required for backup integration test");
 const admin=new Pool({connectionString:process.env.TEST_DATABASE_URL});cleanup.push(()=>admin.end());
 const suffix=randomUUID().replaceAll("-","");const sourceName=`backup_src_${suffix}`,targetName=`backup_dst_${suffix}`;
 for(const name of [sourceName,targetName]){await admin.query(`CREATE DATABASE ${name}`);cleanup.push(()=>admin.query(`DROP DATABASE ${name}`));}
 const sourceUrl=new URL(process.env.TEST_DATABASE_URL);sourceUrl.pathname=`/${sourceName}`;
 const targetUrl=new URL(process.env.TEST_DATABASE_URL);targetUrl.pathname=`/${targetName}`;
 const env={...process.env,DATABASE_URL:sourceUrl.toString()};
 await run(process.execPath,["scripts/migrate-database.mjs"],{env});
 const source=new Pool({connectionString:sourceUrl.toString()});cleanup.push(()=>source.end());
 await source.query("INSERT INTO lives VALUES ('life','{\"lifeId\":\"life\"}','2026-11-02',NULL)");
 await source.query("INSERT INTO identity_users(user_id,display_name,created_at) VALUES ('owner','owner',1)");
 await source.query("INSERT INTO joy_orders(id,user_id,product_id,name,credits,amount_fen,demo,channel,status,request_id,created_at,idempotency_key) VALUES ('order','owner','p','p',40,100,0,'WECHAT_H5','SUCCEEDED','r',1,'k')");
 await source.query("INSERT INTO joy_accounts VALUES ('owner',40,0)");
 await source.query("INSERT INTO joy_ledger(user_id,delta,reason,reference,created_at) VALUES ('owner',40,'trial','owner',1)");
 const dir=await mkdtemp(path.join(tmpdir(),"findjoy-backup-"));cleanup.push(()=>rm(dir,{recursive:true,force:true}));
 await chmod(dir,0o755);
 await expect(run(process.execPath,["scripts/backup-database.mjs"],{env:{...env,FINDJOY_BACKUP_DIR:dir}})).rejects.toThrow();
 await chmod(dir,0o700);
 await expect(run(process.execPath,["scripts/backup-database.mjs"],{env:{...env,FINDJOY_BACKUP_DIR:dir,FINDJOY_PG_BIN:dir}})).rejects.toThrow();
 expect(await readdir(dir)).toEqual([]);
 const result=await run(process.execPath,["scripts/backup-database.mjs"],{env:{...env,FINDJOY_BACKUP_DIR:dir}});
 const {archive}=JSON.parse(result.stdout);expect((await stat(archive)).mode&0o077).toBe(0);
 expect((await stat(archive+".json")).mode&0o077).toBe(0);
 const original=await readFile(archive);
 const restoreEnv={...env,RESTORE_DATABASE_URL:targetUrl.toString(),FINDJOY_RESTORE_ARCHIVE:archive,FINDJOY_RESTORE_EMPTY_TARGET:"yes"};
 await expect(run(process.execPath,["scripts/restore-database.mjs"],{env:{...restoreEnv,RESTORE_DATABASE_URL:sourceUrl.toString()}})).rejects.toThrow();
 await writeFile(archive,"corrupt");
 await expect(run(process.execPath,["scripts/restore-database.mjs"],{env:restoreEnv})).rejects.toThrow();
 await writeFile(archive,original);
 await run(process.execPath,["scripts/restore-database.mjs"],{env:restoreEnv});
 const target=new Pool({connectionString:targetUrl.toString()});cleanup.push(()=>target.end());
 expect((await target.query("SELECT amount_fen,status FROM joy_orders")).rows).toEqual([{amount_fen:100,status:"SUCCEEDED"}]);
 expect((await target.query("SELECT available,held FROM joy_accounts")).rows).toEqual([{available:40,held:0}]);
 expect((await target.query("SELECT state FROM lives")).rows).toEqual([{state:'{"lifeId":"life"}'}]);
 expect((await target.query("INSERT INTO joy_ledger(user_id,delta,reason,reference,created_at) VALUES ('owner',0,'test','next',2) RETURNING id::integer")).rows).toEqual([{id:2}]);
 await expect(run(process.execPath,["scripts/restore-database.mjs"],{env:restoreEnv})).rejects.toThrow();
 expect((await target.query("SELECT count(*)::integer AS n FROM joy_ledger")).rows).toEqual([{n:2}]);
},20000);
