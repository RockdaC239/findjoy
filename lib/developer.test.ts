import { beforeEach, expect, it, vi } from "vitest";
import { randomUUID } from "node:crypto";
import { setupTestPostgres } from "./test-postgres";
setupTestPostgres();
const mocks = vi.hoisted(() => ({ user: vi.fn() }));
vi.mock("./auth", () => ({ currentUser: mocks.user, appOrigin: () => "https://findfire.club" }));
import { identityStore } from "./identity-store";
import { commerceStore } from "./commerce-store";
import { isDeveloper, hasDeveloperAccess } from "./developer";
import { GET } from "../app/api/developer/route";
import { POST } from "../app/api/developer/credits/route";
beforeEach(() => mocks.user.mockResolvedValue(null));
const request = (key = randomUUID(), origin = "https://findfire.club") => new Request("https://findfire.club/findjoy/api/developer/credits", { method: "POST", headers: { origin, "Idempotency-Key": key }, body: JSON.stringify({ credits: 999999, userId: "someone-else", phone: "15200297440" }) });
it("checks only the verified server account phone, including the country prefix", async () => {
  const owner = await identityStore.resolveUser("test", "owner", "owner", "+8615200297440");
  const stranger = await identityStore.resolveUser("test", "stranger", "15200297440");
  expect(await isDeveloper(owner)).toBe(true);
  expect(await isDeveloper(stranger)).toBe(false);
  expect(await isDeveloper(null)).toBe(false);
});
it("只在本人的调试模式开启时才放开开发能力", async () => {
  const owner = await identityStore.resolveUser("test", "owner", "owner", "+8615200297440");
  const stranger = await identityStore.resolveUser("test", "stranger", "15200297440");
  expect(await hasDeveloperAccess(owner, "findjoy_developer=1")).toBe(true);
  expect(await hasDeveloperAccess(owner, "findjoy_developer=1; findjoy_mock=1")).toBe(true);
  expect(await hasDeveloperAccess(owner, null)).toBe(false);
  expect(await hasDeveloperAccess(owner, "findjoy_developer=0")).toBe(false);
  expect(await hasDeveloperAccess(stranger, "findjoy_developer=1")).toBe(false);
  expect(await hasDeveloperAccess(null, "findjoy_developer=1")).toBe(false);
});
it("rejects guests, other users and cross-site grants", async () => {
  expect((await GET()).status).toBe(401);
  expect((await POST(request())).status).toBe(401);
  const stranger = await identityStore.resolveUser("test", "stranger");
  mocks.user.mockResolvedValue(stranger);
  expect((await GET()).status).toBe(403);
  expect((await POST(request())).status).toBe(403);
  const owner = await identityStore.resolveUser("test", "owner", "owner", "15200297440");
  mocks.user.mockResolvedValue(owner);
  expect((await POST(request(randomUUID(), "https://evil.example"))).status).toBe(403);
  expect((await commerceStore.balance(owner.id)).available).toBe(0);
});
it("grants exactly 1000 points to self once for concurrent retries and records the ledger", async () => {
  const owner = await identityStore.resolveUser("test", "owner", "owner", "15200297440");
  mocks.user.mockResolvedValue(owner);
  const key = randomUUID();
  const responses = await Promise.all([POST(request(key)), POST(request(key))]);
  expect(responses.map(response => response.status)).toEqual([200, 200]);
  expect((await commerceStore.balance(owner.id)).available).toBe(1000);
  expect(await commerceStore.ledger(owner.id)).toHaveLength(1);
  expect((await commerceStore.ledger(owner.id))[0].reason).toBe("developer_grant");
});
