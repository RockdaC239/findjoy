-- Epoch timestamps use bigint; JSON remains text to preserve existing save payloads.
CREATE TABLE identity_users (
  user_id text PRIMARY KEY,
  display_name text NOT NULL,
  created_at bigint NOT NULL,
  phone text,
  custom_name integer NOT NULL DEFAULT 0 CHECK (custom_name IN (0,1))
);
CREATE TABLE identity_links (
  issuer text NOT NULL,
  subject text NOT NULL,
  user_id text NOT NULL REFERENCES identity_users(user_id),
  PRIMARY KEY (issuer, subject)
);
CREATE TABLE identity_sessions (
  token_hash text PRIMARY KEY,
  user_id text NOT NULL REFERENCES identity_users(user_id),
  expires_at bigint NOT NULL
);
CREATE INDEX identity_sessions_expiry ON identity_sessions(expires_at);
CREATE TABLE identity_login_transactions (
  token_hash text PRIMARY KEY,
  payload text NOT NULL,
  expires_at bigint NOT NULL
);
CREATE INDEX identity_login_transactions_expiry ON identity_login_transactions(expires_at);
CREATE TABLE lives (
  life_id text PRIMARY KEY,
  state text NOT NULL,
  updated_at text NOT NULL,
  user_id text
);
CREATE INDEX lives_user_updated ON lives(user_id, updated_at DESC);
CREATE TABLE transcripts (
  life_id text PRIMARY KEY,
  messages text NOT NULL,
  updated_at text NOT NULL
);
CREATE TABLE joy_accounts (
  user_id text PRIMARY KEY,
  available integer NOT NULL DEFAULT 0 CHECK (available >= 0),
  held integer NOT NULL DEFAULT 0 CHECK (held >= 0)
);
CREATE TABLE joy_ledger (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL,
  delta integer NOT NULL,
  reason text NOT NULL,
  reference text NOT NULL,
  created_at bigint NOT NULL,
  UNIQUE (reason, reference)
);
CREATE INDEX joy_ledger_user ON joy_ledger(user_id, id DESC);
CREATE TABLE joy_orders (
  id text PRIMARY KEY,
  user_id text NOT NULL,
  product_id text NOT NULL,
  name text NOT NULL,
  credits integer NOT NULL,
  amount_fen integer NOT NULL,
  demo integer NOT NULL CHECK (demo IN (0,1)),
  channel text NOT NULL,
  status text NOT NULL DEFAULT 'CREATED',
  request_id text NOT NULL,
  request_body text,
  pay_url text,
  expires_at text,
  created_at bigint NOT NULL,
  platform_id text UNIQUE,
  idempotency_key text NOT NULL,
  UNIQUE (user_id, idempotency_key)
);
CREATE INDEX joy_orders_user ON joy_orders(user_id, created_at DESC);
CREATE TABLE joy_order_checks (order_id text PRIMARY KEY, checked_at bigint NOT NULL);
CREATE TABLE joy_payment_attempts (order_id text PRIMARY KEY, request_id text NOT NULL);
CREATE TABLE joy_payment_events (event_id text PRIMARY KEY, order_id text NOT NULL, created_at bigint NOT NULL);
CREATE TABLE joy_life_operations (
  id text PRIMARY KEY,
  user_id text NOT NULL,
  life_id text NOT NULL,
  idempotency_key text NOT NULL,
  request_hash text NOT NULL,
  status text NOT NULL,
  expires_at bigint NOT NULL,
  cost_points integer NOT NULL DEFAULT 20,
  UNIQUE (user_id, idempotency_key)
);
CREATE INDEX joy_life_operations_expiry ON joy_life_operations(expires_at) WHERE status='pending';
CREATE TABLE joy_generation_locks (
  life_id text PRIMARY KEY,
  user_id text NOT NULL,
  token text NOT NULL,
  expires_at bigint NOT NULL
);
CREATE INDEX joy_generation_locks_expiry ON joy_generation_locks(expires_at);
CREATE TABLE joy_endings (life_id text PRIMARY KEY, user_id text NOT NULL, ending text NOT NULL);
CREATE TABLE joy_rate_limits (key text PRIMARY KEY, count integer NOT NULL, expires_at bigint NOT NULL);
CREATE INDEX joy_rate_limits_expiry ON joy_rate_limits(expires_at);
-- Imported SQLite units are normalized by the import command, never by request handlers.
CREATE TABLE joy_migrations (name text PRIMARY KEY);
